class Command(BaseCommand):
    help = 'Наполняет энциклопедию начальным набором категорий и статей.'

    def add_arguments(self, parser):
        parser.add_argument(
            '--reset', action='store_true', help='Удалить существующие статьи и категории перед загрузкой.'
        )

    @transaction.atomic
    def handle(self, *args, **opts):
        if opts['reset']:
            LearningTrack.objects.all().delete()
            Article.objects.all().delete()
            KnowledgeCategory.objects.all().delete()
            self.stdout.write(self.style.WARNING('Очистил энциклопедию и практикум.'))

        # Категории
        cats_by_topic = {}
        for topic, name, icon, desc, order in CATEGORIES:
            cat, created = KnowledgeCategory.objects.get_or_create(
                topic=topic,
                defaults={'name': name, 'icon': icon, 'description': desc, 'order': order},
            )
            if not created:
                cat.name, cat.icon, cat.description, cat.order = name, icon, desc, order
                cat.save()
            cats_by_topic[topic] = cat

        # Статьи
        created_count = 0
        for art in ARTICLES:
            cat = cats_by_topic[art['topic']]
            obj, created = Article.objects.update_or_create(
                title=art['title'],
                defaults={
                    'category': cat,
                    'summary': art['summary'].strip(),
                    'body': art['body'].strip(),
                    'reading_minutes': art['reading_minutes'],
                    'order': art['order'],
                    'related_components_note': art.get('related', ''),
                    'is_published': True,
                },
            )
            if created:
                created_count += 1
            materials = ARTICLE_MATERIALS.get(art['title']) or default_materials_for_topic(art['topic'])
            for material in materials:
                ArticleMaterial.objects.update_or_create(
                    article=obj,
                    title=material['title'],
                    defaults={
                        'material_type': material.get('material_type', 'external'),
                        'description': material.get('description', ''),
                        'url': material.get('url', ''),
                        'order': material.get('order', 100),
                        'is_public': material.get('is_public', True),
                    },
                )
            has_inline = obj.materials.filter(
                material_type__in=['image', 'animation', 'video'],
                is_public=True,
            ).exists()
            if not has_inline:
                material = default_inline_material_for_topic(art['topic'])
                ArticleMaterial.objects.update_or_create(
                    article=obj,
                    title=material['title'],
                    defaults={
                        'material_type': material.get('material_type', 'image'),
                        'description': material.get('description', ''),
                        'url': material.get('url', ''),
                        'order': material.get('order', 90),
                        'is_public': True,
                    },
                )

        # Практикум
        lesson_count = 0
        task_count = 0
        for track_data in LEARNING_TRACKS:
            track, _ = LearningTrack.objects.update_or_create(
                title=track_data['title'],
                defaults={
                    'slug': track_data.get('slug', ''),
                    'summary': track_data['summary'],
                    'level': track_data.get('level', 'basic'),
                    'order': track_data.get('order', 100),
                    'is_published': True,
                },
            )
            for lesson_data in track_data.get('lessons', []):
                article = None
                article_query = lesson_data.get('article_query')
                if article_query:
                    article = Article.objects.filter(title__icontains=article_query).first()

                lesson, _ = LearningLesson.objects.update_or_create(
                    slug=lesson_data.get('slug', ''),
                    defaults={
                        'track': track,
                        'title': lesson_data['title'],
                        'summary': lesson_data['summary'],
                        'theory': lesson_data['theory'],
                        'formula': lesson_data.get('formula', ''),
                        'article': article,
                        'action_url': lesson_data.get('action_url', '/simulation/'),
                        'action_label': lesson_data.get('action_label', 'Открыть симулятор'),
                        'estimated_minutes': lesson_data.get('estimated_minutes', 8),
                        'order': lesson_data.get('order', 100),
                        'is_published': True,
                    },
                )
                lesson_count += 1
                for task_data in lesson_data.get('tasks', []):
                    LearningTask.objects.update_or_create(
                        lesson=lesson,
                        title=task_data['title'],
                        defaults={
                            'task_type': task_data['task_type'],
                            'prompt': task_data['prompt'],
                            'rubric': task_data.get('rubric', {}),
                            'order': task_data.get('order', 100),
                            'is_required': task_data.get('is_required', True),
                        },
                    )
                    task_count += 1

        total = Article.objects.count()
        materials_total = ArticleMaterial.objects.count()
        self.stdout.write(
            self.style.SUCCESS(
                f'OK: категорий {len(CATEGORIES)}, статей в базе {total}, материалов {materials_total}, '
                f'уроков {lesson_count}, заданий {task_count} (создано статей: {created_count})'
            )
        )
