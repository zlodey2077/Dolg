ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'docs'


def clean(text: str) -> str:
    return ' '.join((text or '').split())


def latest_source_docx() -> Path:
    candidates = [
        p for p in DOCS.glob('Диплом_DOLG_домашняя_версия_3_редакция_*.docx') if 'актуализ' not in p.name
    ]
    if not candidates:
        raise FileNotFoundError('Не найдена рабочая копия диплома в docs/')
    return sorted(candidates, key=lambda p: p.stat().st_mtime, reverse=True)[0]


def style_or_normal(doc: Document, style_name: str) -> str:
    return style_name if style_name in [s.name for s in doc.styles] else 'Normal'


def set_paragraph_text(paragraph: Paragraph, text: str) -> None:
    paragraph.clear()
    paragraph.add_run(text)


def find_para(doc: Document, prefix: str) -> Paragraph:
    for paragraph in doc.paragraphs:
        if clean(paragraph.text).startswith(prefix):
            return paragraph
    raise ValueError(f'Не найден абзац: {prefix}')


def find_para_contains(doc: Document, needle: str) -> Paragraph | None:
    for paragraph in doc.paragraphs:
        if needle in clean(paragraph.text):
            return paragraph
    return None


def insert_paragraph_after(anchor: Paragraph, text: str = '', style: str | None = None) -> Paragraph:
    new_p = OxmlElement('w:p')
    anchor._p.addnext(new_p)
    paragraph = Paragraph(new_p, anchor._parent)
    if style:
        paragraph.style = style
    if text:
        paragraph.add_run(text)
    return paragraph


def set_cell_text(cell: _Cell, text: str, bold: bool = False) -> None:
    cell.text = ''
    paragraph = cell.paragraphs[0]
    run = paragraph.add_run(text)
    run.bold = bold


def insert_table_after(
    anchor: Paragraph, caption: str, headers: list[str], rows: list[list[str]]
) -> Paragraph:
    caption_para = insert_paragraph_after(anchor, caption, 'Normal')
    table = anchor._parent.add_table(rows=1, cols=len(headers), width=Inches(6.3))
    try:
        table.style = 'Table Grid'
    except KeyError:
        pass

    for i, header in enumerate(headers):
        set_cell_text(table.rows[0].cells[i], header, bold=True)
    for row in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row):
            set_cell_text(cells[i], value)

    # add_table() appends the table to the document body. Move it after the caption.
    table_xml = table._tbl
    table_xml.getparent().remove(table_xml)
    caption_para._p.addnext(table_xml)
    tail = OxmlElement('w:p')
    table_xml.addnext(tail)
    return Paragraph(tail, caption_para._parent)


def remove_between(start: Paragraph, end: Paragraph) -> None:
    node = start._p.getnext()
    while node is not None and node is not end._p:
        next_node = node.getnext()
        node.getparent().remove(node)
        node = next_node


def replace_section(doc: Document, start_prefix: str, end_prefix: str, blocks: list[dict]) -> Paragraph:
    start = find_para(doc, start_prefix)
    end = find_para(doc, end_prefix)
    remove_between(start, end)
    anchor = start
    for block in blocks:
        kind = block['type']
        if kind == 'p':
            anchor = insert_paragraph_after(anchor, block['text'], block.get('style', 'Normal'))
        elif kind == 'list':
            for item in block['items']:
                anchor = insert_paragraph_after(anchor, item, 'List Paragraph')
        elif kind == 'table':
            anchor = insert_table_after(anchor, block['caption'], block['headers'], block['rows'])
        elif kind == 'code':
            code_style = style_or_normal(doc, 'DOLG Code')
            for line in block['text'].strip('\n').splitlines():
                anchor = insert_paragraph_after(anchor, line, code_style)
        else:
            raise ValueError(f'Неизвестный тип блока: {kind}')
    return anchor


def add_note_after_once(doc: Document, needle: str, note: str) -> None:
    if any(note in clean(p.text) for p in doc.paragraphs):
        return
    paragraph = find_para_contains(doc, needle)
    if paragraph is None:
        return
    insert_paragraph_after(paragraph, note, 'Normal')


def replace_text_in_paragraphs(doc: Document, old: str, new: str) -> None:
    for paragraph in doc.paragraphs:
        if old in paragraph.text:
            set_paragraph_text(paragraph, paragraph.text.replace(old, new))


