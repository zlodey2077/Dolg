def validate_document(path: Path) -> dict[str, object]:
    doc = Document(path)
    headings = [clean(p.text) for p in doc.paragraphs if p.style.name.startswith('Heading') and clean(p.text)]
    chapter3 = [h for h in headings if h.startswith('ГЛАВА 3')]
    chapter2_tables = [p.text for p in doc.paragraphs if clean(p.text).startswith('Таблица 2.')]
    appendix = any('Дополнение от 10.05.2026' in clean(p.text) for p in doc.paragraphs)
    return {
        'paragraphs': len(doc.paragraphs),
        'tables': len(doc.tables),
        'headings': headings,
        'chapter3': chapter3,
        'chapter2_table_captions': len(chapter2_tables),
        'has_appendix_20260510': appendix,
    }


