def insert_code(doc: Document, anchor: Paragraph, code: str) -> Paragraph:
    code_style = style_or_normal(doc, 'DOLG Code')
    for line in code.strip('\n').splitlines():
        anchor = insert_paragraph_after(anchor, line.rstrip(), code_style)
    return anchor


def iter_all_paragraphs(doc: Document):
    for paragraph in doc.paragraphs:
        yield paragraph
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                yield from cell.paragraphs


def apply_20260512_fact_updates(doc: Document) -> None:
    replacements = {
        '72 товара': '89 товаров',
        '72 сейчас': '89 сейчас',
        '26 РЭБ-компонентов': '43 РЭБ-компонента',
        '12 демо-схем': '12 демонстрационных схем',
        'справочные материалы и учебный контент': 'энциклопедия, статьи, внутренние ссылки и вложенные материалы',
        'Статьи и категории по электронике для учебного и демонстрационного сценария': (
            '21 статья по 6 категориям, 22 дополнительных материала, внутренние ссылки, изображения, gif-анимации, видео и файлы'
        ),
    }
    for paragraph in iter_all_paragraphs(doc):
        text = paragraph.text
        updated = text
        for old, new in replacements.items():
            updated = updated.replace(old, new)
        if updated != text:
            paragraph.clear()
            paragraph.add_run(updated)


