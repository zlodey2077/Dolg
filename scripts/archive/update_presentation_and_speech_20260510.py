def build_presentation(source: Path) -> None:
    backup_dir = DOCS / 'presentation_backups'
    backup_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    shutil.copy2(source, backup_dir / f'{source.stem}_backup_{timestamp}{source.suffix}')

    source_prs = Presentation(str(source))
    if len(source_prs.slides) != 10:
        raise ValueError(f'Ожидалось 10 слайдов, найдено: {len(source_prs.slides)}')

    # The legacy PPTX is used as a source and is backed up, but the final deck is
    # assembled as a clean Office file. This avoids carrying over broken package
    # parts from old exported presentations while preserving the slide count.
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    blank_layout = prs.slide_layouts[6]
    for data, renderer in zip(SLIDES, RENDERERS):
        slide = prs.slides.add_slide(blank_layout)
        renderer(slide, data)

    prs.save(OUT_PPTX)
    shutil.copy2(OUT_PPTX, DESKTOP_OUT_PPTX)


def set_doc_cell(cell, text: str, bold=False):
    text = normalize_text(str(text))
    cell.text = ''
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    run.bold = bold
    run.font.name = 'Times New Roman'
    run.font.size = Pt(11)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER


def setup_doc(doc: Document) -> None:
    section = doc.sections[0]
    section.orientation = WD_ORIENT.PORTRAIT
    section.page_width = Cm(21)
    section.page_height = Cm(29.7)
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)
    styles = doc.styles
    styles['Normal'].font.name = 'Times New Roman'
    styles['Normal'].font.size = Pt(12)
    for style_name in ['Heading 1', 'Heading 2', 'Heading 3']:
        styles[style_name].font.name = 'Times New Roman'
        styles[style_name].font.bold = True


def add_doc_paragraph(doc: Document, text: str, size=12, bold=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = Cm(1.25)
    p.paragraph_format.line_spacing = 1.5
    run = p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.bold = bold
    return p


def build_speech_doc() -> None:
    doc = Document()
    setup_doc(doc)
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run('Речь к защите и возможные вопросы по дипломной работе DOLG')
    run.bold = True
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    add_doc_paragraph(
        doc,
        'Документ подготовлен как сопровождение к обновленной презентации. Речь рассчитана примерно на 8-10 минут и следует порядку слайдов без изменения их количества.',
        size=12,
    )

    doc.add_heading('1. Речь по слайдам', level=1)
    table = doc.add_table(rows=1, cols=3)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Table Grid'
    hdr = table.rows[0].cells
    set_doc_cell(hdr[0], 'Слайд', bold=True)
    set_doc_cell(hdr[1], 'Смысловой блок', bold=True)
    set_doc_cell(hdr[2], 'Текст выступления', bold=True)
    table.columns[0].width = Cm(1.8)
    table.columns[1].width = Cm(4.2)
    table.columns[2].width = Cm(11.8)
    for idx, (topic, text) in enumerate(SPEECH, 1):
        cells = table.add_row().cells
        set_doc_cell(cells[0], str(idx))
        set_doc_cell(cells[1], topic)
        set_doc_cell(cells[2], text)

    doc.add_page_break()
    doc.add_heading('2. Возможные вопросы и ответы', level=1)
    qa_table = doc.add_table(rows=1, cols=3)
    qa_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    qa_table.style = 'Table Grid'
    hdr = qa_table.rows[0].cells
    set_doc_cell(hdr[0], 'N', bold=True)
    set_doc_cell(hdr[1], 'Возможный вопрос', bold=True)
    set_doc_cell(hdr[2], 'Краткий ответ', bold=True)
    for idx, (question, answer) in enumerate(QUESTIONS, 1):
        cells = qa_table.add_row().cells
        set_doc_cell(cells[0], str(idx))
        set_doc_cell(cells[1], question)
        set_doc_cell(cells[2], answer)

    doc.save(OUT_DOCX)


def build_markdown() -> None:
    lines = [
        '# Речь к защите и возможные вопросы по дипломной работе DOLG',
        '',
        'Речь рассчитана примерно на 8-10 минут и следует порядку обновленной презентации.',
        '',
        '## Речь по слайдам',
        '',
    ]
    for idx, (topic, text) in enumerate(SPEECH, 1):
        lines.extend([f'### Слайд {idx}. {normalize_text(topic)}', normalize_text(text), ''])
    lines.extend(['## Возможные вопросы и ответы', ''])
    for idx, (question, answer) in enumerate(QUESTIONS, 1):
        lines.extend([f'{idx}. **{normalize_text(question)}**', f'   {normalize_text(answer)}', ''])
    OUT_MD.write_text('\n'.join(lines), encoding='utf-8')


def validate_outputs() -> None:
    expected = [OUT_PPTX, DESKTOP_OUT_PPTX, OUT_DOCX, OUT_MD]
    for path in expected:
        if not path.exists() or path.stat().st_size == 0:
            raise RuntimeError(f'Файл не создан: {path}')
    for path in [OUT_PPTX, OUT_DOCX]:
        with zipfile.ZipFile(path) as archive:
            broken = archive.testzip()
            if broken:
                raise RuntimeError(f'Поврежденный файл внутри {path}: {broken}')
    prs = Presentation(str(OUT_PPTX))
    if len(prs.slides) != 11:
        raise RuntimeError(f'После обновления изменилось число слайдов: {len(prs.slides)}')


def main() -> None:
    source = find_source_pptx()
    build_presentation(source)
    build_speech_doc()
    build_markdown()
    validate_outputs()
    print(f'Source: {source}')
    print(f'Presentation: {OUT_PPTX}')
    print(f'Desktop copy: {DESKTOP_OUT_PPTX}')
    print(f'Speech DOCX: {OUT_DOCX}')
    print(f'Speech MD: {OUT_MD}')


if __name__ == '__main__':
    main()
