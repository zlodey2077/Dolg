def find_source_pptx() -> Path:
    hinted = DESKTOP / SOURCE_HINT
    if hinted.exists():
        return hinted
    candidates = [
        path
        for path in DESKTOP.glob('*.pptx')
        if not path.name.startswith('~$') and 'презентац' in path.name.lower()
    ]
    if not candidates:
        candidates = [path for path in DESKTOP.glob('*.pptx') if not path.name.startswith('~$')]
    if not candidates:
        raise FileNotFoundError('Не найден исходный PPTX на рабочем столе.')
    return max(candidates, key=lambda path: path.stat().st_size)


def clear_slide(slide) -> None:
    for shape in list(slide.shapes):
        shape._element.getparent().remove(shape._element)


def add_shape(slide, shape_type, x, y, w, h, fill=None, line=None, radius=False):
    shape = slide.shapes.add_shape(shape_type, x, y, w, h)
    if fill is not None:
        shape.fill.solid()
        shape.fill.fore_color.rgb = fill
    else:
        shape.fill.background()
    if line is None:
        shape.line.fill.background()
    else:
        shape.line.color.rgb = line
        shape.line.width = PptPt(1)
    return shape


def set_run(run, size=18, color=SLATE, bold=False, font=FONT_BODY):
    run.font.name = font
    run.font.size = PptPt(size)
    run.font.color.rgb = color
    run.font.bold = bold


def add_textbox(slide, x, y, w, h, text='', size=18, color=SLATE, bold=False, align=PP_ALIGN.LEFT):
    text = normalize_text(str(text))
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.margin_left = PptPt(4)
    tf.margin_right = PptPt(4)
    tf.margin_top = PptPt(2)
    tf.margin_bottom = PptPt(2)
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    set_run(run, size=size, color=color, bold=bold)
    return box


def add_multiline(slide, x, y, w, h, lines, size=16, color=SLATE, bullet=False, spacing=5):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.margin_left = PptPt(6)
    tf.margin_right = PptPt(6)
    tf.margin_top = PptPt(2)
    tf.margin_bottom = PptPt(2)
    for index, line in enumerate(lines):
        p = tf.paragraphs[0] if index == 0 else tf.add_paragraph()
        line = normalize_text(str(line))
        p.text = f'• {line}' if bullet else line
        p.space_after = PptPt(spacing)
        for run in p.runs:
            set_run(run, size=size, color=color)
    return box


