def add_image_contain(slide, image_path: Path, x, y, w, h, border=True):
    if not image_path.exists():
        add_card(slide, x, y, w, h, 'Изображение не найдено', str(image_path), RED)
        return None
    if border:
        add_shape(slide, MSO_SHAPE.ROUNDED_RECTANGLE, x, y, w, h, PANEL, LINE)
    with Image.open(image_path) as img:
        iw, ih = img.size
    box_ratio = w / h
    img_ratio = iw / ih
    if img_ratio >= box_ratio:
        pic_w = w - Inches(0.18)
        pic_h = int(pic_w / img_ratio)
    else:
        pic_h = h - Inches(0.18)
        pic_w = int(pic_h * img_ratio)
    left = x + int((w - pic_w) / 2)
    top = y + int((h - pic_h) / 2)
    return slide.shapes.add_picture(str(image_path), left, top, width=pic_w, height=pic_h)


def style_cell(cell, text, size=10, bold=False, color=SLATE, fill=None, align=PP_ALIGN.CENTER):
    text = normalize_text(str(text))
    cell.text = ''
    if fill is not None:
        cell.fill.solid()
        cell.fill.fore_color.rgb = fill
    cell.vertical_anchor = MSO_ANCHOR.MIDDLE
    p = cell.text_frame.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    set_run(run, size=size, color=color, bold=bold)
    cell.text_frame.margin_left = PptPt(3)
    cell.text_frame.margin_right = PptPt(3)
    cell.text_frame.margin_top = PptPt(2)
    cell.text_frame.margin_bottom = PptPt(2)


def add_table(slide, rows, x, y, w, h, col_widths=None, font_size=9):
    table_shape = slide.shapes.add_table(len(rows), len(rows[0]), x, y, w, h)
    table = table_shape.table
    if col_widths:
        for index, width in enumerate(col_widths):
            table.columns[index].width = width
    for row_index, row in enumerate(rows):
        for col_index, value in enumerate(row):
            if row_index == 0:
                style_cell(
                    table.cell(row_index, col_index),
                    value,
                    size=font_size,
                    bold=True,
                    color=RGBColor(255, 255, 255),
                    fill=NAVY,
                )
            elif col_index == 0:
                style_cell(
                    table.cell(row_index, col_index),
                    value,
                    size=font_size,
                    bold=True,
                    color=NAVY,
                    fill=RGBColor(226, 232, 240),
                    align=PP_ALIGN.LEFT,
                )
            else:
                fill = RGBColor(255, 255, 255) if row_index % 2 else RGBColor(241, 245, 249)
                style_cell(table.cell(row_index, col_index), value, size=font_size, color=SLATE, fill=fill)
    return table_shape


